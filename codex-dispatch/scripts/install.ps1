# 在 ~/.local/bin（已在 PATH 中）生成两个转发入口，指向本仓库的脚本；重复运行会覆盖，安全。
# 入口只做转发，改仓库里的脚本即生效，不需要重新安装；只有仓库搬家时才要重跑。
$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot
$bin = Join-Path $HOME '.local\bin'
New-Item -ItemType Directory -Force $bin | Out-Null

# Git Bash 入口：bash 需要 /d/... 形式的路径，且文件必须是 LF 行尾、无 BOM。
$posix = '/' + $repo.Substring(0, 1).ToLower() + $repo.Substring(2).Replace('\', '/')
$bashShim = "#!/usr/bin/env bash`n# Generated by codex-worker/install.ps1: forwards to the repo script.`nexec `"$posix/codex-worker`" `"`$@`"`n"
[IO.File]::WriteAllText((Join-Path $bin 'codex-worker'), $bashShim, [Text.UTF8Encoding]::new($false))

# cmd / PowerShell 入口：保持纯 ASCII（cmd 按 GBK 代码页解析 .cmd 文件）。
$cmdShim = "@echo off`r`nrem Generated by codex-worker/install.ps1: forwards to the repo script.`r`ncall `"$repo\codex-worker.cmd`" %*`r`n"
[IO.File]::WriteAllText((Join-Path $bin 'codex-worker.cmd'), $cmdShim, [Text.Encoding]::ASCII)

# 早期版本把 codex-worker.py 直接放在 ~/.local/bin，清掉以免误以为它还在生效。
Remove-Item (Join-Path $bin 'codex-worker.py') -ErrorAction SilentlyContinue

"已安装入口到 $bin -> $repo"
